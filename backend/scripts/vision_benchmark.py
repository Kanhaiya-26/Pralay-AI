"""Benchmark local Ollama vision models for PRALAY's task on THIS machine.

* Models run strictly one at a time; each is unloaded (keep_alive=0) before the next is loaded.
* Identical images, the application's exact prompt + JSON schema (app.vision.PROMPT/SCHEMA), the same image
  preprocessing (EXIF-upright, max edge VISION_MAX_EDGE) and the same sanitizer (app.vision.sanitize).
* Measures: load time, first / subsequent / average inference, Ollama's own timings, peak RSS of the Ollama
  processes, minimum available system RAM, average/peak CPU, timeouts, errors (incl. out-of-memory), schema
  validity, and rule-based relevance per image category.
* Images: synthetic, generated by this script (no personal media). Add your own licensed images with
  --images DIR (filename prefix = expected category: flood_, heavyrain_, waterlogging_, unrelated_, poor_).

    .venv\\Scripts\\python.exe scripts\\vision_benchmark.py --models qwen2.5vl:3b gemma3:4b --runs 2
"""

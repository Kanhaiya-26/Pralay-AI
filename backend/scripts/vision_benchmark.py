# ------------------------------------------------------------------ synthetic image set
def heavy_rain(seed):
    im = scene(seed, "flood").convert("RGB")
    im = Image.blend(im, Image.new("RGB", im.size, (40, 45, 55)), 0.45)
    d = ImageDraw.Draw(im)
    rnd = random.Random(seed)
    for _ in range(1400):
        x, y = rnd.randint(0, im.width), rnd.randint(0, im.height)
        d.line([(x, y), (x - 6, y + 28)], fill=(200, 205, 215), width=1)
    return im.filter(ImageFilter.GaussianBlur(0.8))


def waterlogging(seed):
    im = scene(seed, "landslide").convert("RGB")  # start from a street-level scene, then add shallow puddles
    base = scene(seed + 1, "flood").convert("RGB")
    im = base.copy()
    d = ImageDraw.Draw(im)
    w, h = im.size
    d.rectangle([0, int(h * 0.6), w, h], fill=(95, 92, 88))  # asphalt
    rnd = random.Random(seed)
    for _ in range(9):
        cx, cy = rnd.randint(40, w - 40), rnd.randint(int(h * 0.68), h - 20)
        rx, ry = rnd.randint(60, 180), rnd.randint(12, 35)
        d.ellipse([cx - rx, cy - ry, cx + rx, cy + ry], fill=(120, 130, 140))
    for _ in range(4):  # parked scooters as dark blocks half in water
        x = rnd.randint(50, w - 120)
        d.rectangle([x, int(h * 0.66), x + 70, int(h * 0.74)], fill=(30, 30, 35))
    return im


def unrelated(seed):
    im = Image.new("RGB", (960, 640), (225, 214, 190))
    d = ImageDraw.Draw(im)
    d.rectangle([0, 420, 960, 640], fill=(120, 80, 50))  # table
    rnd = random.Random(seed)
    d.ellipse([300, 300, 660, 470], fill=(235, 235, 235))  # bowl
    for _ in range(7):  # fruit
        x, y = rnd.randint(340, 600), rnd.randint(250, 330)
        d.ellipse([x - 40, y - 40, x + 40, y + 40], fill=rnd.choice([(220, 40, 40), (250, 180, 30), (90, 170, 60)]))
    d.rectangle([60, 80, 260, 380], fill=(70, 110, 160))  # picture frame on wall
    return im


def poor(seed):
    im = scene(seed, "flood").convert("RGB").resize((72, 48), Image.BILINEAR).resize((960, 640), Image.NEAREST)
    im = Image.blend(im, Image.new("RGB", im.size, (0, 0, 0)), 0.55).filter(ImageFilter.GaussianBlur(3))
    return im


def build_images(out_dir, extra_dir=None):
    out_dir.mkdir(parents=True, exist_ok=True)
    gen = [("flood", lambda: scene(101, "flood")), ("flood", lambda: scene(202, "flood")),
           ("heavyrain", lambda: heavy_rain(303)), ("waterlogging", lambda: waterlogging(404)),
           ("unrelated", lambda: unrelated(505)), ("poor", lambda: poor(606))]
    items = []
    for i, (cat, f) in enumerate(gen):
        p = out_dir / f"{cat}_{i}.jpg"
        f().convert("RGB").save(p, "JPEG", quality=90)
        items.append((cat, p, "synthetic"))
    if extra_dir:
        for p in sorted(Path(extra_dir).glob("*.jp*g")):
            items.append((p.stem.split("_")[0].lower(), p, "user-supplied"))
    return items


def encode(path):
    with Image.open(path) as im:
        im = ImageOps.exif_transpose(im).convert("RGB")
        im.thumbnail((vision.VISION_MAX_EDGE, vision.VISION_MAX_EDGE))
        b = io.BytesIO()
        im.save(b, "JPEG", quality=88)
    return base64.b64encode(b.getvalue()).decode()


# ------------------------------------------------------------------ resource sampler
class Sampler(threading.Thread):
    def __init__(self):
        super().__init__(daemon=True)
        self.stop = threading.Event()
        self.peak_rss, self.min_avail, self.cpu = 0, 10 ** 15, []

    def run(self):
        psutil.cpu_percent(None)
        while not self.stop.wait(0.5):
            rss = 0
            for p in psutil.process_iter(["name", "memory_info"]):
                try:
                    if (p.info["name"] or "").lower().startswith("ollama"):
                        rss += p.info["memory_info"].rss
                except (psutil.Error, TypeError):
                    pass
            self.peak_rss = max(self.peak_rss, rss)
            self.min_avail = min(self.min_avail, psutil.virtual_memory().available)
            self.cpu.append(psutil.cpu_percent(None))


# ------------------------------------------------------------------ scoring (rule-based relevance)
def score(cat, out):
    if not out:
        return False, "no output"
    strong = {i["category"] for i in out["disaster_indicators"] if i["strength"] in ("moderate", "strong")}
    text = (out["description"] + " " + " ".join(out["objects_and_conditions"])).lower()
    if cat == "flood":
        return "flood" in strong, f"moderate/strong indicators: {sorted(strong)}"
    if cat == "heavyrain":
        ok = bool(strong & {"flood", "cyclone_storm"}) or "rain" in text
        return ok, f"indicators {sorted(strong)}; mentions rain: {'rain' in text}"
    if cat == "waterlogging":
        ok = "flood" in strong or any(w in text for w in ("water", "puddle", "waterlog"))
        return ok, f"indicators {sorted(strong)}; mentions water: {'water' in text or 'puddle' in text}"
    if cat == "unrelated":
        return not strong, f"false-positive indicators: {sorted(strong)}" if strong else "no disaster indicators (correct)"
    if cat == "poor":
        ok = bool(out["limitations"]) and not any(i["strength"] == "strong" for i in out["disaster_indicators"])
        return ok, f"limitations stated: {bool(out['limitations'])}; strong indicators: {[i['category'] for i in out['disaster_indicators'] if i['strength'] == 'strong']}"
    return False, "unknown category"


def unload(model):
    try:
        httpx.post(f"{URL}/api/generate", json={"model": model, "keep_alive": 0}, timeout=120)
    except httpx.HTTPError:
        pass
    for _ in range(60):
        if not httpx.get(f"{URL}/api/ps", timeout=10).json().get("models"):
            return
        time.sleep(1)


def bench(model, items, runs, timeout):
    for m in httpx.get(f"{URL}/api/ps", timeout=10).json().get("models", []):
        unload(m["name"])
    s = Sampler()
    s.start()
    res = {"model": model, "errors": [], "runs": []}
    t0 = time.time()
    try:
        r = httpx.post(f"{URL}/api/generate", json={"model": model, "prompt": "", "keep_alive": "15m"}, timeout=timeout)
        j = r.json()
        res["load_wall_s"] = round(time.time() - t0, 1)
        res["load_ollama_s"] = round(j.get("load_duration", 0) / 1e9, 1)
        if r.status_code != 200:
            res["errors"].append(f"load HTTP {r.status_code}: {r.text[:200]}")
    except httpx.HTTPError as e:
        res["errors"].append(f"load failed: {type(e).__name__}: {e}")
    ps = httpx.get(f"{URL}/api/ps", timeout=10).json().get("models", [])
    res["ollama_ps"] = [{"name": m["name"], "size_gb": round(m.get("size", 0) / 1e9, 2), "size_vram_gb": round(m.get("size_vram", 0) / 1e9, 2)} for m in ps]
    n = 0
    for rep in range(runs):
        for cat, path, origin in items:
            n += 1
            body = {"model": model, "stream": False, "format": vision.SCHEMA, "options": {"temperature": 0}, "keep_alive": "15m",
                    "messages": [{"role": "user", "content": vision.PROMPT + f"\nThe reporter claims category: flood.", "images": [encode(path)]}]}
            t1 = time.time()
            row = {"n": n, "rep": rep + 1, "image": path.name, "category": cat, "origin": origin}
            try:
                r = httpx.post(f"{URL}/api/chat", json=body, timeout=timeout)
                row["wall_s"] = round(time.time() - t1, 1)
                if r.status_code != 200:
                    row["status"] = "error"
                    row["error"] = f"HTTP {r.status_code}: {r.text[:200]}"
                else:
                    j = r.json()
                    row.update(total_s=round(j.get("total_duration", 0) / 1e9, 1), load_s=round(j.get("load_duration", 0) / 1e9, 2),
                               prompt_tokens=j.get("prompt_eval_count"), out_tokens=j.get("eval_count"),
                               tok_per_s=round(j.get("eval_count", 0) / (j.get("eval_duration", 1) / 1e9), 2) if j.get("eval_duration") else None)
                    content = j.get("message", {}).get("content", "")
                    out, notes = vision.sanitize(content)
                    row["schema_valid"] = out is not None
                    row["sanitizer_notes"] = notes
                    row["status"] = "ok" if out is not None else "malformed"
                    ok, why = score(cat, out)
                    row["relevant"], row["relevance_note"] = ok, why
                    row["output"] = out
            except httpx.TimeoutException:
                row.update(status="timeout", wall_s=round(time.time() - t1, 1))
            except httpx.HTTPError as e:
                row.update(status="error", error=f"{type(e).__name__}: {e}", wall_s=round(time.time() - t1, 1))
            res["runs"].append(row)
            print(f"  [{model}] #{n} {path.name}: {row['status']} {row.get('wall_s')}s relevant={row.get('relevant')}", flush=True)
    s.stop.set()
    s.join()
    walls = [r["wall_s"] for r in res["runs"] if r["status"] == "ok"]
    res.update(peak_ollama_rss_gb=round(s.peak_rss / 1e9, 2), min_available_ram_gb=round(s.min_avail / 1e9, 2),
               cpu_avg_pct=round(statistics.mean(s.cpu), 1) if s.cpu else None, cpu_peak_pct=max(s.cpu) if s.cpu else None,
               first_inference_s=res["runs"][0].get("wall_s") if res["runs"] else None,
               subsequent_avg_s=round(statistics.mean(walls[1:]), 1) if len(walls) > 1 else None,
               avg_inference_s=round(statistics.mean(walls), 1) if walls else None,
               median_inference_s=round(statistics.median(walls), 1) if walls else None,
               completed=len(walls), total=len(res["runs"]),
               schema_valid=sum(1 for r in res["runs"] if r.get("schema_valid")),
               relevant=sum(1 for r in res["runs"] if r.get("relevant")),
               timeouts=sum(1 for r in res["runs"] if r["status"] == "timeout"),
               oom=sum(1 for r in res["runs"] if "memory" in (r.get("error") or "").lower()),
               verdict_stripped=sum(1 for r in res["runs"] if any("authenticity" in x for x in (r.get("sanitizer_notes") or []))))
    unload(model)
    return res


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--models", nargs="+", default=["qwen2.5vl:3b", "gemma3:4b"])
    ap.add_argument("--runs", type=int, default=2)
    ap.add_argument("--timeout", type=float, default=900)
    ap.add_argument("--images", default=None)
    a = ap.parse_args()
    img_dir = ROOT / "reports" / "benchmark_images"
    items = build_images(img_dir, a.images)
    vm = psutil.virtual_memory()
    env = {"cpu": f"{psutil.cpu_count(False)}C/{psutil.cpu_count()}T", "ram_total_gb": round(vm.total / 1e9, 1),
           "ram_available_at_start_gb": round(vm.available / 1e9, 2), "ollama": httpx.get(f"{URL}/api/version", timeout=5).json().get("version"),
           "started": datetime.now(timezone.utc).isoformat(timespec="seconds"), "image_max_edge": vision.VISION_MAX_EDGE}
    print("env:", env, flush=True)
    results = []
    for m in a.models:  # strictly sequential
        print(f"== {m}", flush=True)
        results.append(bench(m, items, a.runs, a.timeout))
    out = {"env": env, "images": [{"category": c, "file": str(p.relative_to(ROOT)) if ROOT in p.parents else str(p), "origin": o} for c, p, o in items],
           "results": results}
    dst = ROOT / "reports" / "model_benchmark_raw.json"
    dst.write_text(json.dumps(out, indent=1, default=str), encoding="utf-8")
    print("saved", dst)


if __name__ == "__main__":
    main()
